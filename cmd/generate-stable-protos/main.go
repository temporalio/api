const (
	apiNextPrefix   = "temporal/api_next/"
	stableAPIPrefix = "temporal/api/"

	draftTagsPath = apiNextPrefix + "protometa/v1/draft.proto"

	generatedHeader = "// Code generated by generate-stable-protos. DO NOT EDIT. \n // @generated \n\n"
)

func main() {
	root := flag.String("root", ".", "directory holding the proto tree; also the sole import path")
	outDir := flag.String("out", "", "directory to write the projected tree into (defaults to -root/ as api is still different from api_next)")
	flag.Parse()

	if info, err := os.Stat(*root); err != nil || !info.IsDir() {
		fmt.Fprintf(os.Stderr, "-root %q must be an existing directory\n", *root)
		os.Exit(1)
	}
	if *outDir == "" {
		*outDir = *root
	}

	if err := stableProtosGenerator(*root, *outDir); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func stableProtosGenerator(root, outDir string) error {
	ctx := context.Background()
	paths, err := getAPINextPaths(root)
	if err != nil {
		return err
	}
	if len(paths) == 0 {
		return fmt.Errorf("no protos found under %q", filepath.Join(root, apiNextPrefix))
	}

	strippedOrder, strippedProtos, comments, err := stripDrafts(ctx, root, paths)
	if err != nil {
		return err
	}

	// import stripping has to happen after the draft-tagged declarations are deleted
	// because unused imports are only detectable after it is re-rendered
	stableProtos, err := organizeImports(ctx, root, strippedOrder, strippedProtos)
	if err != nil {
		return err
	}

	for _, p := range strippedOrder {
		var diagnostics report.Report
		file, _ := parser.Parse(p, source.NewFile(p, stableProtos[stablePath(p)]), &diagnostics)
		if err := comments[p].check(file.Stream()); err != nil {
			return err
		}
	}

	for path, text := range stableProtos {
		stableProtos[path] = generatedHeader + text
	}

	if err := verifyGeneratedProtos(ctx, root, stableProtos); err != nil {
		return err
	}

	return writeFiles(outDir, stableProtos)
}

func stripDrafts(ctx context.Context, root string, paths []string) ([]string, map[string]string, map[string]draftComments, error) {
	// first, lower the api_next set into ir
	results, err := lowerFiles(ctx, baseOpener(root), paths)
	if err != nil {
		return nil, nil, nil, fmt.Errorf("lower api_next corpus: %w", err)
	}

	// need to iterate to find the draft proto- also check
	// for errors while iterating so it doesnt have to be repeated
	byPath := make(map[string]*ir.File, len(paths))
	for i, p := range paths {
		if results[i].Fatal != nil {
			return nil, nil, nil, fmt.Errorf("%s: %w", p, results[i].Fatal)
		}
		irFile := results[i].Value
		if got := irFile.Path(); got != p {
			return nil, nil, nil, fmt.Errorf("internal error: incremental.Run result %d has path %q, expected %q", i, got, p)
		}
		for imp := range seq.Values(irFile.Imports()) {
			// Draft options reached through a public re-export would leak it into the stable tree.
			if imp.Direct && imp.Public && imp.Path() == draftTagsPath {
				return nil, nil, nil, fmt.Errorf("%s: public import of %s is not supported; import it directly", p, draftTagsPath)
			}
		}
		byPath[p] = irFile
	}

	draftFile, ok := byPath[draftTagsPath]
	if !ok {
		return nil, nil, nil, fmt.Errorf("%s not found in the corpus; cannot discover the draft-tag extension set", draftTagsPath)
	}
	tags, err := getDraftTags(draftFile)
	if err != nil {
		return nil, nil, nil, err
	}
	for _, p := range paths {
		if err := validateDraftAnnotations(tags, byPath[p]); err != nil {
			return nil, nil, nil, err
		}
	}

	stableOrder := make([]string, 0, len(paths))
	protoTexts := make(map[string]string, len(paths))
	comments := make(map[string]draftComments, len(paths))
	for _, p := range paths {
		irFile := byPath[p]
		// skip draft.proto itself
		if p == draftTagsPath {
			continue
		}

		dels := findDraftNodes(tags, irFile)
		if comments[p], err = findDraftComments(irFile, dels); err != nil {
			return nil, nil, nil, err
		}
		edits := make([]edit.Edit, len(dels))
		for j, d := range dels {
			edits[j] = edit.Edit{Kind: edit.KindDelete, Target: d}
		}
		if err := edit.ApplyEdits(irFile.AST(), edits); err != nil {
			return nil, nil, nil, fmt.Errorf("delete draft declarations: %s: %w", p, err)
		}
		protoText, err := printFile(irFile)
		if err != nil {
			return nil, nil, nil, fmt.Errorf("print %s: %w", p, err)
		}

		protoTexts[p] = protoText
		stableOrder = append(stableOrder, p)
	}
	return stableOrder, protoTexts, comments, nil
}

// strip unused imports and rename import to stable (api_next -> api)
func organizeImports(ctx context.Context, root string, order []string, texts map[string]string) (map[string]string, error) {
	results, err := lowerFiles(ctx, memOpener(root, texts), order)
	if err != nil {
		return nil, fmt.Errorf("re-lower draft-stripped corpus: %w", err)
	}

	stableTexts := make(map[string]string, len(order))
	for i, p := range order {
		if results[i].Fatal != nil {
			return nil, fmt.Errorf("%s: %w", p, results[i].Fatal)
		}
		irFile := results[i].Value

		var importDels []edit.Edit
		for j := 0; j < irFile.Imports().Len(); j++ {
			imp := irFile.Imports().At(j)
			if !imp.Used && !imp.Decl.IsZero() {
				importDels = append(importDels, edit.Edit{Kind: edit.KindDelete, Target: imp.Decl.AsAny()})
			}
		}
		if err := edit.ApplyEdits(irFile.AST(), importDels); err != nil {
			return nil, fmt.Errorf("prune imports: %s: %w", p, err)
		}
		protoText, err := printFile(irFile)
		if err != nil {
			return nil, fmt.Errorf("print %s: %w", p, err)
		}
		stableTexts[stablePath(p)], err = rewriteImportPaths(protoText)
		if err != nil {
			return nil, fmt.Errorf("rewrite imports in %s: %w", p, err)
		}
	}
	return stableTexts, nil
}

// re-lower one more time to ensure there are no compilation issues
func verifyGeneratedProtos(ctx context.Context, root string, stableTexts map[string]string) error {
	paths := make([]string, 0, len(stableTexts))
	for p := range stableTexts {
		paths = append(paths, p)
	}
	sort.Strings(paths)
	results, err := lowerFiles(ctx, memOpener(root, stableTexts), paths)
	if err != nil {
		return fmt.Errorf("verify stable tree failed: %w", err)
	}
	var jErr error
	for i, r := range results {
		if r.Fatal != nil {
			jErr = errors.Join(jErr, fmt.Errorf("verification failed at file %q: %w", paths[i], r.Fatal))
		}
	}
	return jErr
}

// lowerFiles lowers paths in one session; each pass must construct its opener once.
func lowerFiles(ctx context.Context, opener source.Opener, paths []string) ([]incremental.Result[*ir.File], error) {
	session := &ir.Session{}
	lowerQueries := make([]incremental.Query[*ir.File], len(paths))
	for i, p := range paths {
		lowerQueries[i] = queries.IR{Opener: opener, Session: session, Path: p}
	}
	results, report, err := incremental.Run(ctx, incremental.New(), lowerQueries...)
	if err != nil {
		return nil, err
	}
	if text, hasErrors := errorDiagnostics(report); hasErrors {
		return nil, fmt.Errorf("diagnostics produced :\n%s", text)
	}
	return results, nil
}

// TODO: check if the buf formatter rules can just get pulled into a custom formatter
func printFile(file *ir.File) (string, error) {
	return printer.PrintFile(printer.Options{Format: true, Formatting: printer.Legacy()}, file.AST())
}

func errorDiagnostics(r *report.Report) (renderText string, hasErrors bool) {
	for _, d := range r.Diagnostics {
		if d.Level() <= report.Error {
			hasErrors = true
			break
		}
	}
	if !hasErrors {
		return "", false
	}
	text, _, _ := (report.Renderer{}).RenderString(r)
	return text, true
}

func stablePath(path string) string {
	if rest, ok := strings.CutPrefix(path, apiNextPrefix); ok {
		return stableAPIPrefix + rest
	}
	return path
}

func writeFiles(dir string, files map[string]string) error {
	for path, text := range files {
		dest := filepath.Join(dir, filepath.FromSlash(path))
		if err := os.MkdirAll(filepath.Dir(dest), 0o755); err != nil {
			return err
		}
		if err := os.WriteFile(dest, []byte(text), 0o644); err != nil {
			return fmt.Errorf("write %q: %w", dest, err)
		}
	}
	return nil
}

func getAPINextPaths(root string) ([]string, error) {
	var sources []string
	dir := filepath.Join(root, filepath.FromSlash(apiNextPrefix))
	if err := filepath.WalkDir(dir, func(path string, entry fs.DirEntry, err error) error {
		if err != nil || entry.IsDir() || filepath.Ext(path) != ".proto" {
			return err
		}
		relative, err := filepath.Rel(root, path)
		if err != nil {
			return err
		}
		sources = append(sources, filepath.ToSlash(relative))
		return nil
	}); err != nil {
		return nil, fmt.Errorf("walk %q: %w", dir, err)
	}
	sort.Strings(sources)
	return sources, nil
}

func rewriteImportPaths(text string) (string, error) {
	var diagnostics report.Report
	file, _ := parser.Parse("projected.proto", source.NewFile("projected.proto", text), &diagnostics)
	if diagnostic, hasErrors := errorDiagnostics(&diagnostics); hasErrors {
		return "", fmt.Errorf("parse projected imports: %s", diagnostic)
	}
	// Splice only import-expression spans, preserving option values and comments.
	var out strings.Builder
	start := 0
	for imp := range file.Imports() {
		path := imp.ImportPath().AsLiteral().Token.AsString().Text()
		if !strings.HasPrefix(path, apiNextPrefix) {
			continue
		}
		span := imp.ImportPath().Span()
		offset := 0
		for tok := range file.Stream().All() {
			partSpan := tok.LeafSpan()
			if tok.Kind() != token.String || partSpan.Start < span.Start || partSpan.End > span.End {
				continue
			}
			var part wrapperspb.StringValue
			if err := prototext.Unmarshal([]byte("value: "+partSpan.Text()), &part); err != nil {
				return "", fmt.Errorf("decode import literal: %w", err)
			}
			// The _next suffix can straddle concatenated literals; preserve their comments.
			from := max(len(stableAPIPrefix)-1-offset, 0)
			to := min(len(apiNextPrefix)-1-offset, len(part.Value))
			offset += len(part.Value)
			if from >= to {
				continue
			}
			out.WriteString(text[start:partSpan.Start])
			out.WriteString(strconv.Quote(part.Value[:from] + part.Value[to:]))
			start = partSpan.End
		}
	}
	out.WriteString(text[start:])
	return out.String(), nil
}
