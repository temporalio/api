const generatedHeader = "// Code generated by generate-stable-protos. DO NOT EDIT. \n // @generated \n\n"

type config struct {
	nextDir     string
	stableDir   string
	draftSchema string
	// rpcEndpointAllowlist lists the only RPC positions grandfathered stable endpoint types may occupy.
	rpcEndpointAllowlist rpcEndpointPositions
}

func defaultConfig() config {
	return config{
		nextDir:              "temporal/api_next",
		stableDir:            "temporal/api",
		draftSchema:          "temporal/api_next/protometa/v1/draft.proto",
		rpcEndpointAllowlist: rpcEndpointPositions{},
	}
}

func (cfg config) validatePaths() error {
	for _, arg := range []struct{ flag, path string }{
		{"-next", cfg.nextDir},
		{"-stable", cfg.stableDir},
		{"-draft-schema", cfg.draftSchema},
	} {
		if arg.path == "." || !fs.ValidPath(arg.path) || !filepath.IsLocal(arg.path) || strings.ContainsRune(arg.path, '\\') {
			return fmt.Errorf("%s %q must be a clean, local relative path", arg.flag, arg.path)
		}
	}
	if cfg.nextDir == cfg.stableDir ||
		strings.HasPrefix(cfg.nextDir, cfg.stableDir+"/") ||
		strings.HasPrefix(cfg.stableDir, cfg.nextDir+"/") {
		return fmt.Errorf("-next %q and -stable %q overlap", cfg.nextDir, cfg.stableDir)
	}
	return nil
}

func main() {
	root := flag.String("root", ".", "directory holding the proto tree; also the sole import path")
	outDir := flag.String("out", "", "required output directory (must be empty or nonexistent)")
	cfg := defaultConfig()
	flag.StringVar(&cfg.nextDir, "next", cfg.nextDir, "source proto subdirectory relative to -root")
	flag.StringVar(&cfg.stableDir, "stable", cfg.stableDir, "stable proto subdirectory relative to -out")
	flag.StringVar(&cfg.draftSchema, "draft-schema", cfg.draftSchema, "draft option schema path relative to -root")
	flag.Parse()
	if err := cfg.stableProtosGenerator(context.Background(), *root, *outDir); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func (cfg config) stableProtosGenerator(ctx context.Context, root, outDir string) error {
	if outDir == "" {
		return errors.New("-out is required")
	}
	if err := cfg.validatePaths(); err != nil {
		return err
	}
	if err := os.MkdirAll(outDir, 0o755); err != nil {
		return fmt.Errorf("prepare -out %q: %w", outDir, err)
	}
	out, err := os.OpenRoot(outDir)
	if err != nil {
		return fmt.Errorf("open -out %q: %w", outDir, err)
	}
	defer out.Close()
	entries, err := fs.ReadDir(out.FS(), ".")
	if err != nil {
		return fmt.Errorf("read -out %q: %w", outDir, err)
	}
	if len(entries) != 0 {
		return fmt.Errorf("-out %q must be empty", outDir)
	}
	info, err := os.Stat(root)
	if err != nil {
		return fmt.Errorf("inspect -root %q: %w", root, err)
	}
	if !info.IsDir() {
		return fmt.Errorf("-root %q must be an existing directory", root)
	}

	paths, err := cfg.getAPINextPaths(root)
	if err != nil {
		return err
	}
	if len(paths) == 0 {
		return fmt.Errorf("no protos found under %q", filepath.Join(root, cfg.nextDir))
	}

	strippedProtos, comments, err := cfg.stripDrafts(ctx, root, paths)
	if err != nil {
		return err
	}
	strippedOrder := slices.Sorted(maps.Keys(strippedProtos))

	// Strip unused imports after deleting draft-tagged declarations and re-rendering the protos,
	// because only then can we detect which imports are unused.
	stableProtos, err := cfg.organizeImports(ctx, root, strippedOrder, strippedProtos)
	if err != nil {
		return err
	}

	for _, p := range strippedOrder {
		var diagnostics report.Report
		file, _ := parser.Parse(p, source.NewFile(p, stableProtos[cfg.stablePath(p)]), &diagnostics)
		if err := comments[p].check(file.Stream()); err != nil {
			return err
		}
	}

	for path, text := range stableProtos {
		stableProtos[path] = generatedHeader + text
	}

	if err := verifyGeneratedProtos(ctx, root, stableProtos); err != nil {
		return err
	}

	return writeFiles(out, stableProtos)
}

// loadAPINext lowers the configured source tree, discovers the draft-tag extension set, and
// validates the draft schema rules, returning the explicit annotations it accepted.
func (cfg config) loadAPINext(ctx context.Context, root string, paths []string) (map[string]*ir.File, draftTags, draftAnnotations, error) {
	if !slices.Contains(paths, cfg.draftSchema) {
		paths = slices.Concat(paths, []string{cfg.draftSchema})
	}
	// First, lower the source tree and configured draft schema into IR.
	results, err := lowerFiles(ctx, baseOpener(root), paths)
	if err != nil {
		return nil, draftTags{}, nil, fmt.Errorf("lower %s corpus: %w", cfg.nextDir, err)
	}

	// Check for errors while indexing files by path so we can look up the draft proto in one pass.
	byPath := make(map[string]*ir.File, len(paths))
	for i, p := range paths {
		if results[i].Fatal != nil {
			return nil, draftTags{}, nil, fmt.Errorf("%s: %w", p, results[i].Fatal)
		}
		irFile := results[i].Value
		if got := irFile.Path(); got != p {
			return nil, draftTags{}, nil, fmt.Errorf("internal error: incremental.Run result %d has path %q, expected %q", i, got, p)
		}
		for imp := range seq.Values(irFile.Imports()) {
			// A public re-export of the draft options proto would leak it into the stable tree.
			if imp.Direct && imp.Public && imp.Path() == cfg.draftSchema {
				return nil, draftTags{}, nil, fmt.Errorf("%s: public import of %s is not supported; import it directly", p, cfg.draftSchema)
			}
		}
		byPath[p] = irFile
	}

	draftSchema := byPath[cfg.draftSchema]
	tags, err := getDraftTags(draftSchema)
	if err != nil {
		return nil, draftTags{}, nil, err
	}
	annotations := draftAnnotations{}
	for _, p := range paths {
		f := byPath[p]
		accepted, err := validateDraftAnnotations(tags, f)
		if err != nil {
			return nil, draftTags{}, nil, err
		}
		if len(accepted) > 0 && !f.ImportFor(draftSchema).Direct {
			return nil, draftTags{}, nil, fmt.Errorf("%s: draft annotations require a direct import of %s", p, cfg.draftSchema)
		}
		maps.Copy(annotations, accepted)
	}
	endpointUses := make(rpcEndpointUses)
	for _, p := range paths {
		if err := validateDraftRules(tags, byPath[p], endpointUses, cfg.rpcEndpointAllowlist); err != nil {
			return nil, draftTags{}, nil, err
		}
	}
	return byPath, tags, annotations, nil
}

func (cfg config) stripDrafts(ctx context.Context, root string, paths []string) (map[string]string, map[string]draftComments, error) {
	byPath, tags, _, err := cfg.loadAPINext(ctx, root, paths)
	if err != nil {
		return nil, nil, err
	}

	protoTexts := make(map[string]string, len(paths))
	comments := make(map[string]draftComments, len(paths))
	for _, p := range paths {
		irFile := byPath[p]
		// Omit the configured draft schema from the destination tree.
		if p == cfg.draftSchema {
			continue
		}

		dels := findDraftNodes(tags, irFile)
		if comments[p], err = findDraftComments(irFile, dels); err != nil {
			return nil, nil, err
		}
		edits := make([]edit.Edit, len(dels))
		for j, d := range dels {
			edits[j] = edit.Edit{Kind: edit.KindDelete, Target: d}
		}
		if err := edit.ApplyEdits(irFile.AST(), edits); err != nil {
			return nil, nil, fmt.Errorf("delete draft declarations: %s: %w", p, err)
		}
		protoText, err := printFile(irFile)
		if err != nil {
			return nil, nil, fmt.Errorf("print %s: %w", p, err)
		}

		protoTexts[p] = protoText
	}
	return protoTexts, comments, nil
}

// organizeImports removes unused imports and rewrites source tree imports to destination tree paths.
func (cfg config) organizeImports(ctx context.Context, root string, order []string, texts map[string]string) (map[string]string, error) {
	results, err := lowerFiles(ctx, memOpener(root, texts), order)
	if err != nil {
		return nil, fmt.Errorf("re-lower draft-stripped corpus: %w", err)
	}

	stableTexts := make(map[string]string, len(order))
	for i, p := range order {
		if results[i].Fatal != nil {
			return nil, fmt.Errorf("%s: %w", p, results[i].Fatal)
		}
		irFile := results[i].Value

		var importDels []edit.Edit
		for j := 0; j < irFile.Imports().Len(); j++ {
			imp := irFile.Imports().At(j)
			if !imp.Used && !imp.Decl.IsZero() {
				importDels = append(importDels, edit.Edit{Kind: edit.KindDelete, Target: imp.Decl.AsAny()})
			}
		}
		if err := edit.ApplyEdits(irFile.AST(), importDels); err != nil {
			return nil, fmt.Errorf("prune imports: %s: %w", p, err)
		}
		protoText, err := printFile(irFile)
		if err != nil {
			return nil, fmt.Errorf("print %s: %w", p, err)
		}
		stableTexts[cfg.stablePath(p)], err = cfg.rewriteImportPaths(protoText)
		if err != nil {
			return nil, fmt.Errorf("rewrite imports in %s: %w", p, err)
		}
	}
	return stableTexts, nil
}

// verifyGeneratedProtos lowers the generated protos again to check for compilation errors.
func verifyGeneratedProtos(ctx context.Context, root string, stableTexts map[string]string) error {
	paths := slices.Sorted(maps.Keys(stableTexts))
	results, err := lowerFiles(ctx, memOpener(root, stableTexts), paths)
	if err != nil {
		return fmt.Errorf("verify stable tree failed: %w", err)
	}
	var errs error
	for i, r := range results {
		if r.Fatal != nil {
			errs = errors.Join(errs, fmt.Errorf("verification failed at file %q: %w", paths[i], r.Fatal))
		}
	}
	return errs
}

// lowerFiles lowers paths in one session. Each pass must construct its opener once.
func lowerFiles(ctx context.Context, opener source.Opener, paths []string) ([]incremental.Result[*ir.File], error) {
	session := &ir.Session{}
	lowerQueries := make([]incremental.Query[*ir.File], len(paths))
	for i, p := range paths {
		lowerQueries[i] = queries.IR{Opener: opener, Session: session, Path: p}
	}
	results, report, err := incremental.Run(ctx, incremental.New(), lowerQueries...)
	if err != nil {
		return nil, err
	}
	if text, hasErrors := errorDiagnostics(report); hasErrors {
		return nil, fmt.Errorf("diagnostics produced :\n%s", text)
	}
	return results, nil
}

// printFile formats the file with the legacy formatter.
//
// TODO: Check whether a custom formatter can reuse Buf's formatting rules.
func printFile(file *ir.File) (string, error) {
	return printer.PrintFile(printer.Options{Format: true, Formatting: printer.Legacy()}, file.AST())
}

func errorDiagnostics(r *report.Report) (renderText string, hasErrors bool) {
	for _, d := range r.Diagnostics {
		if d.Level() <= report.Error {
			hasErrors = true
			break
		}
	}
	if !hasErrors {
		return "", false
	}
	text, _, _ := (report.Renderer{}).RenderString(r)
	return text, true
}

func (cfg config) stablePath(path string) string {
	if rest, ok := strings.CutPrefix(path, cfg.nextDir+"/"); ok {
		return cfg.stableDir + "/" + rest
	}
	return path
}

func writeFiles(out *os.Root, files map[string]string) error {
	for _, path := range slices.Sorted(maps.Keys(files)) {
		dest := filepath.FromSlash(path)
		if err := out.MkdirAll(filepath.Dir(dest), 0o755); err != nil {
			return err
		}
		file, err := out.OpenFile(dest, os.O_WRONLY|os.O_CREATE|os.O_EXCL, 0o644)
		if err != nil {
			return err
		}
		_, writeErr := file.WriteString(files[path])
		if err := errors.Join(writeErr, file.Close()); err != nil {
			return fmt.Errorf("write %q: %w", file.Name(), err)
		}
	}
	return nil
}

func (cfg config) getAPINextPaths(root string) ([]string, error) {
	var sources []string
	dir := filepath.Join(root, filepath.FromSlash(cfg.nextDir))
	if err := filepath.WalkDir(dir, func(path string, entry fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if entry.IsDir() {
			return nil
		}
		if path == dir {
			return fmt.Errorf("-next %q must be a directory", cfg.nextDir)
		}
		if filepath.Ext(path) != ".proto" {
			return nil
		}
		relative, err := filepath.Rel(root, path)
		if err != nil {
			return err
		}
		sources = append(sources, filepath.ToSlash(relative))
		return nil
	}); err != nil {
		return nil, fmt.Errorf("walk %q: %w", dir, err)
	}
	sort.Strings(sources)
	return sources, nil
}

func (cfg config) rewriteImportPaths(text string) (string, error) {
	var diagnostics report.Report
	file, _ := parser.Parse("projected.proto", source.NewFile("projected.proto", text), &diagnostics)
	if diagnostic, hasErrors := errorDiagnostics(&diagnostics); hasErrors {
		return "", fmt.Errorf("parse projected imports: %s", diagnostic)
	}
	common := 0
	for common < min(len(cfg.nextDir), len(cfg.stableDir)) && cfg.nextDir[common] == cfg.stableDir[common] {
		common++
	}
	replacement := cfg.stableDir[common:]
	// Splice only import-expression spans, preserving option values and comments.
	var out strings.Builder
	start := 0
	for imp := range file.Imports() {
		path := imp.ImportPath().AsLiteral().Token.AsString().Text()
		if cfg.stablePath(path) == path {
			continue
		}
		span := imp.ImportPath().Span()
		offset := 0
		for tok := range file.Stream().All() {
			partSpan := tok.LeafSpan()
			if tok.Kind() != token.String || partSpan.Start < span.Start || partSpan.End > span.End {
				continue
			}
			var part wrapperspb.StringValue
			if err := prototext.Unmarshal([]byte("value: "+partSpan.Text()), &part); err != nil {
				return "", fmt.Errorf("decode import literal: %w", err)
			}
			// The changed directory segment can straddle concatenated literals. Preserve their comments.
			end := offset + len(part.Value)
			from := max(common-offset, 0)
			to := min(len(cfg.nextDir)-offset, len(part.Value))
			insert := ""
			if offset <= common && common < end {
				insert = replacement
			}
			offset = end
			if from >= to && insert == "" {
				continue
			}
			out.WriteString(text[start:partSpan.Start])
			out.WriteString(quoteLike(partSpan.Text(), part.Value[:from]+insert+part.Value[to:]))
			start = partSpan.End
		}
	}
	out.WriteString(text[start:])
	return out.String(), nil
}

// quoteLike quotes s with the quote character of the literal it replaces. The printer
// sorts imports by their raw text, so changing the quote would reorder them on the next
// run.
func quoteLike(literal, s string) string {
	quoted := strconv.Quote(s)
	if !strings.HasPrefix(literal, "'") {
		return quoted
	}
	body := strings.ReplaceAll(quoted[1:len(quoted)-1], `\"`, `"`)
	return "'" + strings.ReplaceAll(body, "'", `\'`) + "'"
}
